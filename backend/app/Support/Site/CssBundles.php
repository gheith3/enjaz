<?php

namespace App\Support\Site;

use App\View\Components\Site\Layout;
use Illuminate\Support\Str;

/**
 * One stylesheet per page instead of ~27: resources/site/css-bundles/<key>.css @imports the page's design
 * stylesheets in the exact order of Layout::stylesheetsFor() (config/site.php "styles"), and Vite inlines them
 * into a single file at build time. The design files themselves stay separate and are edited as before.
 *
 * The bundles are generated (php artisan site:css-bundles) and committed, because the Docker frontend stage
 * builds with Node only. A test fails when a bundle no longer matches config/site.php.
 */
class CssBundles
{
    public const DIR = 'resources/site/css-bundles';

    /** Bundle name for a page styles key (null = the shared stylesheets only). */
    public static function name(?string $key): string
    {
        return $key ?? '_shared';
    }

    /** Path of the bundle, relative to the app root (as Vite and @vite() expect). */
    public static function path(?string $key): string
    {
        return self::DIR.'/'.self::name($key).'.css';
    }

    /** @return list<string|null> every styles key in config/site.php, plus null for pages without one */
    public static function keys(): array
    {
        return [null, ...array_keys(config('site.styles', []))];
    }

    /** The bundle's expected contents: @import of each stylesheet, in order. */
    public static function contents(?string $key): string
    {
        $imports = array_map(
            fn (string $file) => '@import "../'.Str::after($file, 'resources/site/').'";',
            Layout::stylesheetsFor($key),
        );

        return '/* Generated by `php artisan site:css-bundles` from config/site.php (styles.'.self::name($key)."). Do not edit:\n"
            ." * edit the design stylesheets themselves, or the page's list in config/site.php and run the command again. */\n"
            .implode("\n", $imports)."\n";
    }

    /** The page's stylesheets: its bundle when it exists, otherwise the separate files (a new page before the command runs). */
    public static function for(?string $key): array
    {
        return is_file(base_path(self::path($key))) ? [self::path($key)] : Layout::stylesheetsFor($key);
    }
}
